// Menu transcribed from the salon's printed price lists (Ladies / Mens).
// Single source of truth: scripts/gen-seed.mjs turns this into supabase/seed.sql,
// and the site falls back to it whenever the API is unreachable.
//
// Section: { id, title, icon, cols|null, items: [{ name, note?, prices: [number|null, ...] }] }
// `cols` names the price columns for multi-price tables (e.g. Rika / Aloe / Choco).

const list = (id, title, icon, rows) => ({
  id,
  title,
  icon,
  cols: null,
  items: rows.map(([name, price, note]) => ({ name, note, prices: [price] })),
})

const table = (id, title, icon, cols, rows) => ({
  id,
  title,
  icon,
  cols,
  items: rows.map(([name, ...prices]) => ({ name, prices })),
})

